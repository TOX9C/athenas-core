#!/usr/bin/env node

import { readFile } from 'node:fs/promises'
import { readdir } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const buildSource = await readFile(resolve(root, 'src-tauri/build.rs'), 'utf8')
const capabilitySource = await readFile(resolve(root, 'src-tauri/capabilities/default.json'), 'utf8')
const permissionDir = resolve(root, 'src-tauri/permissions/autogenerated')

const commandMatch = buildSource.match(/const COMMANDS: &\[&str\] = &\[([\s\S]*?)\];/)
if (!commandMatch) throw new Error('Could not find COMMANDS manifest in src-tauri/build.rs')
const commands = [...commandMatch[1].matchAll(/"([a-zA-Z0-9_]+)"/g)].map(([, command]) => command)
const duplicates = (values) => [...new Set(values.filter((value, index) => values.indexOf(value) !== index))]
const duplicateCommands = duplicates(commands)
const expectedCommands = new Set(commands)
const expectedPermissions = new Set(commands.map((command) => `allow-${command.replaceAll('_', '-')}`))
const files = await readdir(permissionDir)
const tomlFiles = files.filter((file) => file.endsWith('.toml'))
const normalizedStems = tomlFiles.map((file) => file.slice(0, -5).replaceAll('_', '-'))
const duplicateStems = duplicates(normalizedStems)
const actualStems = new Set(normalizedStems)
const capability = new Set([...capabilitySource.matchAll(/"(allow-[a-z0-9-]+)"/g)].map(([, permission]) => permission))

const missingFiles = [...expectedPermissions].filter((permission) => !actualStems.has(permission.slice('allow-'.length))).sort()
const extraFiles = [...actualStems].filter((stem) => ![...expectedPermissions].some((permission) => permission === `allow-${stem}`)).sort()
const missingCapability = [...expectedPermissions].filter((permission) => !capability.has(permission)).sort()
const extraCapability = [...capability].filter((permission) => !expectedPermissions.has(permission)).sort()
const malformed = []

for (const file of tomlFiles) {
  const source = await readFile(resolve(permissionDir, file), 'utf8')
  const allow = [...source.matchAll(/commands\.allow\s*=\s*\[\s*"([a-zA-Z0-9_]+)"\s*\]/g)].map(([, command]) => command)
  const deny = [...source.matchAll(/commands\.deny\s*=\s*\[\s*"([a-zA-Z0-9_]+)"\s*\]/g)].map(([, command]) => command)
  const stem = file.slice(0, -5).replaceAll('_', '-')
  const expectedCommand = [...expectedCommands].find((command) => command.replaceAll('_', '-') === stem)
  if (!expectedCommand || allow.length !== 1 || deny.length !== 1 || allow[0] !== expectedCommand || deny[0] !== expectedCommand) {
    malformed.push(file)
  }
}

if (duplicateCommands.length || duplicateStems.length || missingFiles.length || extraFiles.length || missingCapability.length || extraCapability.length || malformed.length) {
  console.error('Tauri permission drift detected.')
  if (duplicateCommands.length) console.error(`Duplicate build commands: ${duplicateCommands.join(', ')}`)
  if (duplicateStems.length) console.error(`Duplicate generated permission stems: ${duplicateStems.join(', ')}`)
  if (missingFiles.length) console.error(`Missing generated allow files: ${missingFiles.join(', ')}`)
  if (extraFiles.length) console.error(`Extra generated allow files: ${extraFiles.join(', ')}`)
  if (missingCapability.length) console.error(`Missing default capability entries: ${missingCapability.join(', ')}`)
  if (extraCapability.length) console.error(`Extra default capability entries: ${extraCapability.join(', ')}`)
  if (malformed.length) console.error(`Malformed permission contents: ${malformed.join(', ')}`)
  process.exit(1)
}

console.log(`Tauri permissions are consistent (${commands.length} commands).`)
